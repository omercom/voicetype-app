import Foundation
import AppKit
import CoreGraphics
import ApplicationServices

public enum InjectionMethod: String, Sendable {
    case accessibility = "accessibility"
    case transientClipboard = "transient_clipboard"
    case none = "none"
}

/// macOS için modern "Akıllı Hibrit Şelale" (Hybrid Waterfall) metin enjeksiyon yöneticisi.
///
/// 1. Seviye (Altın Standart): Doğrudan Erişilebilirlik API'si (AXUIElementSetAttributeValue - kAXSelectedTextAttribute).
///    - Standart macOS uygulamalarında (Safari, Notlar, Slack, Word, TextEdit, Pages vb.) metni doğrudan imlece enjekte eder.
///    - Sistem panosuna ASLA dokunmaz; pano kirlenmez, pano yöneticileri (Raycast, Maccy, Alfred vb.) tetiklenmez.
///    - 0 milisaniye gecikme ile anında çalışır.
///
/// 2. Seviye (Yedek Hat / Fallback): Akıllı Geçici Pano (Transient Clipboard).
///    - Doğrudan erişime izin vermeyen uygulamalarda (Terminal, canvas editörleri vb.) devreye girer.
///    - Kullanıcının mevcut panosunu tüm formatlarıyla (görseller, dosyalar, RTF) eksiksiz yedekler.
///    - Metni topluluk standardı olan `org.nspasteboard.TransientType` ve `org.nspasteboard.AutoGeneratedType` işaretleyicileriyle yazar.
///    - Cmd+V simüle edildikten sonra orijinal panoyu tam sadakatle geri yükler.
public class TextInjector {
    public static let shared = TextInjector()

    private let queue = DispatchQueue(label: "com.voicetyping.textinjector", qos: .userInteractive)

    // Topluluk standardı nspasteboard.org geçici pano tipleri
    public static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    public static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    public static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")

    private init() {}

    // MARK: - Clipboard Snapshot & Full Fidelity Restore

    public struct ClipboardItemSnapshot {
        public let types: [NSPasteboard.PasteboardType]
        public let dataByType: [NSPasteboard.PasteboardType: Data]

        public init(types: [NSPasteboard.PasteboardType], dataByType: [NSPasteboard.PasteboardType: Data]) {
            self.types = types
            self.dataByType = dataByType
        }
    }

    /// Panodaki tüm öğeleri ve tüm veri formatlarını (metin, resim, dosya URL, RTF, HTML) kayıpsız yedekler.
    public func captureClipboardSnapshot() -> [ClipboardItemSnapshot] {
        let pb = NSPasteboard.general
        guard let items = pb.pasteboardItems, !items.isEmpty else { return [] }

        var snapshot: [ClipboardItemSnapshot] = []
        for item in items {
            var dataMap: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) {
                    dataMap[type] = data
                }
            }
            if !dataMap.isEmpty {
                snapshot.append(ClipboardItemSnapshot(types: item.types, dataByType: dataMap))
            }
        }
        return snapshot
    }

    /// Alınan tam sadakatli panoyu orijinal format ve veri tipleriyle birlikte NSPasteboard.general'a geri yükler.
    public func restoreClipboardSnapshot(_ snapshot: [ClipboardItemSnapshot]) {
        let pb = NSPasteboard.general
        pb.clearContents()
        guard !snapshot.isEmpty else { return }

        var newItems: [NSPasteboardItem] = []
        for itemSnap in snapshot {
            let item = NSPasteboardItem()
            for type in itemSnap.types {
                if let data = itemSnap.dataByType[type] {
                    item.setData(data, forType: type)
                }
            }
            newItems.append(item)
        }
        pb.writeObjects(newItems)
    }

    public func getClipboard() -> String {
        return NSPasteboard.general.string(forType: .string) ?? ""
    }

    public func setClipboard(_ text: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
    }

    /// Pano yöneticilerinin (Raycast, Maccy vb.) geçmişe kaydetmesini engelleyen transient işaretleyicilerle yazar.
    public func setTransientClipboard(_ text: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: Self.transientType)
        item.setData(Data(), forType: Self.autoGeneratedType)
        pb.writeObjects([item])
    }

    // MARK: - Level 1: Direct Accessibility Insertion (Zero Clipboard Contact)

    /// Aktif odaklanılmış UI elemanının imleç konumuna metni doğrudan enjekte eder.
    /// Başarılı olursa `true` döner ve panoya hiç dokunulmaz.
    public func insertViaAccessibility(text: String) -> Bool {
        guard AXIsProcessTrusted() else { return false }

        let systemWide = AXUIElementCreateSystemWide()
        var focusedRef: CFTypeRef?
        let focusResult = AXUIElementCopyAttributeValue(systemWide, kAXFocusedUIElementAttribute as CFString, &focusedRef)
        guard focusResult == .success, let focusedElement = focusedRef else {
            return false
        }

        let element = focusedElement as! AXUIElement

        // kAXSelectedTextAttribute değerinin değiştirilebilir (settable) olup olmadığını doğrula
        var isSettable: DarwinBoolean = false
        let settableResult = AXUIElementIsAttributeSettable(element, kAXSelectedTextAttribute as CFString, &isSettable)
        guard settableResult == .success, isSettable.boolValue else {
            return false
        }

        // Metni doğrudan imlece bas (seçim varsa yerine yazar, yoksa imleç konumuna ekler)
        let value = text as CFTypeRef
        let setResult = AXUIElementSetAttributeValue(element, kAXSelectedTextAttribute as CFString, value)
        return setResult == .success
    }

    // MARK: - Level 2: Keyboard Simulation (Cmd + V)

    public func simulateCmdV() {
        let vKeyCode: CGKeyCode = 9 // 'v' tuşu

        guard let eventDown = CGEvent(keyboardEventSource: nil, virtualKey: vKeyCode, keyDown: true),
              let eventUp = CGEvent(keyboardEventSource: nil, virtualKey: vKeyCode, keyDown: false) else {
            let script = "tell application \"System Events\" to keystroke \"v\" using command down"
            if let appleScript = NSAppleScript(source: script) {
                var error: NSDictionary?
                appleScript.executeAndReturnError(&error)
            }
            return
        }

        eventDown.flags = .maskCommand
        let tapLocation: CGEventTapLocation = AXIsProcessTrusted() ? .cghidEventTap : .cgSessionEventTap
        eventDown.post(tap: tapLocation)

        Thread.sleep(forTimeInterval: 0.020)

        eventUp.flags = []
        eventUp.post(tap: tapLocation)
    }

    // MARK: - Unified Smart Hybrid Injection

    /// Akıllı metin enjeksiyonunun ana giriş noktası.
    /// Önce doğrudan Erişilebilirlik ile imlece basmayı dener (0ms, sıfır pano teması).
    /// Başarısız olursa geçici ve korumalı pano yöntemine (transient fallback) geçer.
    @discardableResult
    public func inject(
        text: String,
        pasteDelayMs: Int = 20
    ) -> InjectionMethod {
        guard !text.isEmpty else { return .none }

        // 1. Aşama: Doğrudan Erişilebilirlik ile İmlece Basma (%90+ uygulamada anında başarı)
        if insertViaAccessibility(text: text) {
            return .accessibility
        }

        // 2. Aşama: Yedek Hat - Geçici ve Tam Korumalı Pano Yapıştırma
        let snapshot = captureClipboardSnapshot()
        setTransientClipboard(text)

        queue.async { [weak self] in
            guard let self = self else { return }
            if pasteDelayMs > 0 {
                Thread.sleep(forTimeInterval: Double(pasteDelayMs) / 1000.0)
            }
            self.simulateCmdV()

            // Yapıştırma işlendikten hemen sonra kullanıcının orijinal panosunu kayıpsız geri yükle
            Thread.sleep(forTimeInterval: 0.08)
            DispatchQueue.main.async {
                self.restoreClipboardSnapshot(snapshot)
            }
        }

        return .transientClipboard
    }

    /// Geriye dönük uyumluluk için paste metodu
    @discardableResult
    public func paste(
        text: String,
        restoreClipboard: Bool = true,
        pasteDelayMs: Int = 20
    ) -> Bool {
        let result = inject(text: text, pasteDelayMs: pasteDelayMs)
        return result != .none
    }
}
